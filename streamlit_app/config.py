def get_all_quizzes():
    """Get all quizzes as a flat list."""
    all_quizzes = []
    for grade in QUIZ_DATA:
        for unit in QUIZ_DATA[grade]:
            all_quizzes.extend(QUIZ_DATA[grade][unit])
    return all_quizzes


def get_quizzes_by_grade(grade):
    """Get all quizzes for a specific grade."""
    quizzes = []
    if grade in QUIZ_DATA:
        for unit in QUIZ_DATA[grade]:
            quizzes.extend(QUIZ_DATA[grade][unit])
    return quizzes


def get_quiz_by_id(quiz_id):
    """Get a specific quiz by its ID."""
    for quiz in get_all_quizzes():
        if quiz["id"] == quiz_id:
            return quiz
    return None


def search_quizzes(query):
    """Search quizzes by keyword."""
    query = query.lower()
    results = []
    for quiz in get_all_quizzes():
        if (query in quiz["title"].lower() or
            query in quiz["description"].lower() or
            any(query in k.lower() for k in quiz["keywords"])):
            results.append(quiz)
    return results
